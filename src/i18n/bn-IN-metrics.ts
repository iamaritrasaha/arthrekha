export function localizeMetricDefinition(definition: MetricDefinition, language: 'en-IN' | 'bn-IN'): MetricDefinition {
  if (language !== 'bn-IN') return definition;
  const translation = bengaliMetricTranslations[definition.id];
  if (!translation) return definition;
  return {
    ...definition,
    displayName: translation.displayName,
    shortName: translation.shortName ?? translation.displayName,
    explanation: translation.explanation,
    shortDescription: translation.explanation.short,
    longDescription: translation.explanation.simple,
    formula: translation.formula ?? definition.formula,
    caveats: translation.caveats ?? definition.caveats,
  };
}
